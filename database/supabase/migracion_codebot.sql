CREATE TABLE tutor_conversations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users (id) ON UPDATE CASCADE ON DELETE CASCADE,
  title VARCHAR(120) NOT NULL DEFAULT 'Nueva conversación',
  created_at TIMESTAMP(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  archived_at TIMESTAMP(0) NULL
);
CREATE INDEX idx_tutor_conversations_user_updated
  ON tutor_conversations (user_id, updated_at DESC);

CREATE TABLE tutor_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversation_id BIGINT NOT NULL REFERENCES tutor_conversations (id) ON UPDATE CASCADE ON DELETE CASCADE,
  user_id INTEGER NOT NULL REFERENCES users (id) ON UPDATE CASCADE ON DELETE CASCADE,
  role VARCHAR(12) NOT NULL CHECK (role IN ('user', 'model')),
  content TEXT NOT NULL,
  created_at TIMESTAMP(0) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_tutor_messages_conversation_created
  ON tutor_messages (conversation_id, created_at);
CREATE INDEX idx_tutor_messages_user_created
  ON tutor_messages (user_id, created_at);

CREATE OR REPLACE FUNCTION tutor_touch_conversation() RETURNS trigger AS $$
BEGIN
  UPDATE tutor_conversations SET updated_at = CURRENT_TIMESTAMP WHERE id = NEW.conversation_id;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_tutor_message_touch_conversation
AFTER INSERT ON tutor_messages
FOR EACH ROW EXECUTE FUNCTION tutor_touch_conversation();
